def set_lang(code):
    """Set interface language."""
    _current["lang"] = code if code in TRANSLATIONS else "en"


def get_lang():
    return _current["lang"]


def t(key, **kwargs):
    """Translate a string with fallback to English."""
    lang = _current["lang"]
    s = TRANSLATIONS.get(lang, {}).get(key)
    if s is None:
        s = TRANSLATIONS["en"].get(key, key)
    if kwargs:
        try:
            s = s.format(**kwargs)
        except Exception:
            pass
    return s


def has_translation(code):
    return code in TRANSLATIONS